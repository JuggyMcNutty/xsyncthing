#!/usr/bin/env python3
"""Generates src/core/blowfish_constants.inc: Blowfish's initial P-array and S-boxes, which are the fractional
hexadecimal digits of pi (Schneier, 1993). Computed here with integer arithmetic (Machin's formula) rather than
copied, so the file can be checked by running this script again."""
import sys

WORDS = 18 + 4 * 256
DIGITS = WORDS * 8 + 16  # hex digits, with guard digits


def arctan_inv(x, one):
    # arctan(1/x) * one, by its Taylor series
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total


def main():
    bits = DIGITS * 4 + 64
    one = 1 << bits
    pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
    frac = pi - 3 * one  # the fractional part, scaled by 2^bits
    words = []
    for _ in range(WORDS):
        frac <<= 32
        w = frac >> bits
        frac -= w << bits
        words.append(w)
    p, s = words[:18], words[18:]
    out = ["// Generated by tools/gen/blowfish_constants.py: the hexadecimal digits of pi. Do not edit.", "",
           "static const uint32_t kBlowfishP[18] = {"]
    for i in range(0, 18, 6):
        out.append("\t" + ", ".join(f"0x{w:08x}" for w in p[i:i + 6]) + ",")
    out.append("};")
    out.append("")
    out.append("static const uint32_t kBlowfishS[4][256] = {")
    for b in range(4):
        out.append("\t{")
        box = s[b * 256:(b + 1) * 256]
        for i in range(0, 256, 6):
            out.append("\t\t" + ", ".join(f"0x{w:08x}" for w in box[i:i + 6]) + ",")
        out.append("\t},")
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
